"""Parity gate for the Rust core rewrite (docs/rust-core-plan.md).

tests/golden/manifest.json was generated by the pure-Python pipeline; every
engine must reproduce it exactly (decompressed NBT hash, meta JSON, and the
diagnostics of known-bad inputs). Regenerate only for an intentional output
change: `uv run python scripts/golden.py`.
"""
from __future__ import annotations

import importlib.metadata
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _golden_module():
    spec = importlib.util.spec_from_file_location("golden", ROOT / "scripts" / "golden.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["golden"] = module
    spec.loader.exec_module(module)
    return module


def test_core_extension_matches_package_version():
    from starlark_to_nbt import _core
    assert _core.version() == importlib.metadata.version("starlark-to-nbt")


def test_outputs_match_golden_manifest():
    golden = _golden_module()
    expected = json.loads(golden.MANIFEST.read_text(encoding="utf-8"))
    if not golden.LIBRARY.is_dir():
        expected["builds"] = {k: v for k, v in expected["builds"].items() if not k.startswith("library/")}
    current = golden.generate()
    for section in ("builds", "failures"):
        assert current[section].keys() == expected[section].keys(), section
        drifted = sorted(name for name in expected[section]
                         if current[section][name] != expected[section][name])
        assert not drifted, f"{section} drifted: {drifted}"
